
DROP TABLE users if exists;
DROP TABLE item_categories if exists;
DROP TABLE items if exists;
DROP TABLE item_images if exists;
DROP TABLE item_favorites if exists;
DROP TABLE chats if exists;
DROP TABLE messages if exists;

CREATE TABLE users(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_name VARCHAR(30) NOT NULL CHECK(CHAR_LENGTH(TRIM(profile_name)) >= 1),
    account_name VARCHAR(30) NOT NULL UNIQUE CHECK(CHAR_LENGTH(TRIM(account_name)) >= 5),
    password_hash TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE item_categories(
    id SMALLINT GENERATED BY DEFAULT AS IDentitY PRIMARY KEY,
    name VARCHAR(100) NOT NULL
);

-- status: 1(DRAFT)/2(ACTIVE)/3(RESERVED)/4(DELETED)
CREATE TABLE items(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poster_id BIGINT REFERENCES users(id) NOT NULL,
    title VARCHAR(100) NOT NULL CHECK(CHAR_LENGTH(TRIM(title)) >= 5),
    category_id SMALLINT NOT NULL DEFAULT 1 REFERENCES item_categories(id),
    description TEXT CHECK(CHAR_LENGTH(description) <= 4000),
    price INTEGER NOT NULL DEFAULT 0 CHECK(price >= 0),
    location_id INTEGER REFERENCES geodb_locations(id) NOT NULL,
    postcode VARCHAR(5) NOT NULL CHECK(postcode ~ '^[0-9]{5}$'),
    location_extra_info VARCHAR(50) DEFAULT '',
    status SMALLINT DEFAULT 1 NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE item_images(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image BLOB NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    item_id BIGINT REFERENCES items(id) NOT NULL,
    display_order SMALLINT NOT NULL DEFAULT 0
);


CREATE TABLE item_favorites(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id),
    item_id BIGINT REFERENCES items(id)
);

CREATE TABLE chats(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
    item_id BIGINT REFERENCES items(id) NOT NULL,
    poster_id BIGINT REFERENCES users(id) NOT NULL,
    interested_user_id BIGINT REFERENCES users(id) NOT NULL,
    first_deleted_by_user_id BIGINT REFERENCES  users(id)
--     created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE messages(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
    chat_id BIGINT REFERENCES chats(id) NOT NULL,
    sender_id BIGINT REFERENCES users(id) NOT NULL,
    content TEXT NOT NULL CHECK(
        CHAR_LENGTH(content)>0
        AND CHAR_LENGTH(content) <= 4000),
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);